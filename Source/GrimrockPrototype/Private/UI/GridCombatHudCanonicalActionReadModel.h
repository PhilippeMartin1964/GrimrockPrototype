#pragma once

#include "Runtime/Combat/GridDualWieldPolicy.h"
#include "Runtime/Items/GridItemSubsystem.h"
#include "../Runtime/Combat/GridCanonicalActionIconReadModel.h"

/** Presentation-only, fail-closed canonical equipment-action icon bridge.
 * True means a registered ItemId was handled, INCLUDING rejected stale or
 * invalid sources. The caller must never borrow an old DA_Weapon icon then.
 * False means unknown/non-equipment and preserves the legacy/quick-item path.
 */
struct FGridCombatHudCanonicalActionReadModel
{
	static bool Apply(const UGridItemSubsystem* Registry, FName SourceDefinitionId,
		bool bResolvedAction, const FGridItemInstance* EquippedSource,
		FGridAvailableCombatAction& InOutAction)
	{
		if (!IsValid(Registry) || !Registry->HasCanonicalItem(SourceDefinitionId) ||
			(bResolvedAction && InOutAction.Definition.SourcePolicy != EGridCombatActionSourcePolicy::Equipment))
		{
			return false;
		}

		// When registered, neither the old item Icon nor a visual-catalogue
		// ItemIcon is ever an action image. Clear any earlier legacy override
		// even when the runtime action/source is no longer available.
		InOutAction.Definition.Icon.Reset();
		if (!bResolvedAction || !EquippedSource || !EquippedSource->IsValid() ||
			EquippedSource->ItemDefinitionId != SourceDefinitionId ||
			EquippedSource->OwnerType != EGridItemOwnerType::EquipmentSlot ||
			EquippedSource->EquipmentSlot != InOutAction.SourceEquipmentSlot ||
			!EquippedSource->OwnerGuid.IsValid() ||
			EquippedSource->OwnerCharacterIndex != InOutAction.CharacterIndex ||
			(InOutAction.CharacterId.IsValid() &&
				InOutAction.CharacterId != EquippedSource->OwnerGuid) ||
			(InOutAction.SourceRuntimeId.IsValid() &&
				InOutAction.SourceRuntimeId != EquippedSource->RuntimeObjectId))
		{
			return true;
		}
		FGridResolvedItem Canonical;
		if (!Registry->ResolveItem(SourceDefinitionId, EquippedSource->ItemLevel, Canonical) ||
			!Canonical.bIsArmament ||
			!Canonical.Weapon.HasAttackSourceInHand(InOutAction.SourceEquipmentSlot))
		{
			return true;
		}
		if (InOutAction.Definition.DisplayName.IsEmpty())
		{
			InOutAction.Definition.DisplayName = Canonical.DisplayName;
		}
		if (InOutAction.Definition.Description.IsEmpty())
		{
			InOutAction.Definition.Description = Canonical.Description;
		}

		// Normal individual attacks must be bound to this exact physical
		// GUID/hand and level. The dual composite is generated by the
		// two-weapon policy, so it has no per-item ActionBinding.
		if (InOutAction.Definition.ActionId != FGridDualWieldPolicy::ActionId())
		{
			FGridResolvedBoundAction Bound;
			if (!Registry->ResolveAttackFromEquippedInstance(*EquippedSource,
				InOutAction.Definition.ActionId, InOutAction.SourceEquipmentSlot,
				EquippedSource->RuntimeObjectId, EquippedSource->OwnerGuid,
				EquippedSource->OwnerCharacterIndex, Bound))
			{
				return true;
			}
		}

		const EGridEquippedWeaponActionIconKind Kind =
			FGridCanonicalActionIconReadModel::Classify(Canonical, InOutAction.Definition);
		InOutAction.Definition.Icon = Registry->FindEquippedActionIcon(Kind);
		return true;
	}
};
