# VALIDATION-AUTO01.11 — silent Windows Task Scheduler action; Windows PowerShell 5.1.
# The generated launcher lives in the user's local state, not in the project checkout.
# WScript.Shell.Run(..., 0, True): no visible console AND keep task alive until build ends.

function Get-UEValidationSilentPaths {
    param([Parameter(Mandatory=$true)][string]$StateRoot)
    return @{
        PowerShell = (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe')
        WScript = (Join-Path $env:SystemRoot 'System32\wscript.exe')
        Launcher = (Join-Path $StateRoot 'UEValidationSilentLauncher.vbs')
    }
}

function New-UEValidationSilentAction {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory=$true)][string]$RepositoryRoot,
        [Parameter(Mandatory=$true)][string]$StateRoot,
        [Parameter(Mandatory=$true)][string]$PowerShellArguments
    )
    $Paths = Get-UEValidationSilentPaths -StateRoot $StateRoot
    foreach ($Executable in @($Paths.PowerShell, $Paths.WScript)) {
        if (-not (Test-Path -LiteralPath $Executable -PathType Leaf)) {
            throw 'VALIDATION-AUTO01.11: Windows scripting executable unavailable.'
        }
    }
    if ([string]::IsNullOrWhiteSpace($PowerShellArguments) -or $PowerShellArguments.Contains("`r") -or
        $PowerShellArguments.Contains("`n")) {
        throw 'VALIDATION-AUTO01.11: invalid PowerShell arguments.'
    }

    $Bootstrap = Join-Path $RepositoryRoot 'Scripts\UEValidationBootstrap.ps1'
    $Required = @(
        ('-File "' + $Bootstrap + '"'),
        ('-RepositoryRoot "' + $RepositoryRoot + '"'),
        ('-StateRoot "' + $StateRoot + '"')
    )
    foreach ($Token in $Required) {
        if ($PowerShellArguments.IndexOf($Token, [StringComparison]::OrdinalIgnoreCase) -lt 0) {
            throw 'VALIDATION-AUTO01.11: unexpected bootstrap command; no task mutation.'
        }
    }
    $Command = '"' + $Paths.PowerShell + '" ' + $PowerShellArguments
    $ProbeCommand = '"' + $Paths.PowerShell + '" -NoLogo -NoProfile -NonInteractive -Command "exit 0"'
    $EncodedCommand = $Command.Replace('"', '""')
    $EncodedProbe = $ProbeCommand.Replace('"', '""')
    $Source = @(
        "' VALIDATION-AUTO01.11 / GrimrockPrototype / generated by trusted installer or validation agent",
        'Option Explicit',
        'Dim Runner, ExitCode',
        'Set Runner = CreateObject("WScript.Shell")',
        'If WScript.Arguments.Count = 1 Then',
        '    If WScript.Arguments(0) = "--self-test" Then',
        ('        ExitCode = Runner.Run("' + $EncodedProbe + '", 0, True)'),
        '        WScript.Quit ExitCode',
        '    End If',
        'End If',
        ('ExitCode = Runner.Run("' + $EncodedCommand + '", 0, True)'),
        'WScript.Quit ExitCode'
    ) -join "`r`n"

    New-Item -ItemType Directory -Path $StateRoot -Force | Out-Null
    $PreviousSource = $null
    if (Test-Path -LiteralPath $Paths.Launcher -PathType Leaf) {
        $PreviousSource = Get-Content -LiteralPath $Paths.Launcher -Raw -ErrorAction Stop
        if (-not $PreviousSource.StartsWith("' VALIDATION-AUTO01.11 / GrimrockPrototype /")) {
            throw 'VALIDATION-AUTO01.11: unknown existing launcher; overwrite refused.'
        }
    }
    $Temp = $Paths.Launcher + '.tmp'
    try {
        # Unicode BOM keeps absolute paths intact, including accented Windows user names.
        Set-Content -LiteralPath $Temp -Value $Source -Encoding Unicode -ErrorAction Stop
        Move-Item -LiteralPath $Temp -Destination $Paths.Launcher -Force -ErrorAction Stop
        $SelfTestArgs = '//B //Nologo "' + $Paths.Launcher + '" --self-test'
        $Probe = Start-Process -FilePath $Paths.WScript -ArgumentList $SelfTestArgs -WindowStyle Hidden `
            -Wait -PassThru -ErrorAction Stop
        if ($Probe.ExitCode -ne 0) {
            throw 'VALIDATION-AUTO01.11: WSH launcher self-test failed.'
        }
    }
    catch {
        if ($null -ne $PreviousSource) {
            Set-Content -LiteralPath $Paths.Launcher -Value $PreviousSource -Encoding Unicode
        }
        else {
            Remove-Item -LiteralPath $Paths.Launcher -Force -ErrorAction SilentlyContinue
        }
        throw
    }
    finally {
        Remove-Item -LiteralPath $Temp -Force -ErrorAction SilentlyContinue
    }
    return New-ScheduledTaskAction -Execute $Paths.WScript `
        -Argument ('//B //Nologo "' + $Paths.Launcher + '"') -WorkingDirectory $RepositoryRoot
}

function Assert-UEValidationSilentAction {
    param(
        [Parameter(Mandatory=$true)]$Action,
        [Parameter(Mandatory=$true)][string]$RepositoryRoot,
        [Parameter(Mandatory=$true)][string]$StateRoot
    )
    $Paths = Get-UEValidationSilentPaths -StateRoot $StateRoot
    $ExpectedArgs = '//B //Nologo "' + $Paths.Launcher + '"'
    if ($Action.Execute -ine $Paths.WScript -or $Action.Arguments -cne $ExpectedArgs -or
        $Action.WorkingDirectory -ine $RepositoryRoot -or
        -not (Test-Path -LiteralPath $Paths.Launcher -PathType Leaf)) {
        throw 'VALIDATION-AUTO01.11: scheduled task action does not match silent launcher.'
    }
    $Content = Get-Content -LiteralPath $Paths.Launcher -Raw -ErrorAction Stop
    if (-not $Content.StartsWith("' VALIDATION-AUTO01.11 / GrimrockPrototype /") -or
        -not $Content.Contains('Runner.Run(') -or
        -not $Content.Contains(', 0, True)') -or
        -not $Content.Contains('UEValidationBootstrap.ps1')) {
        throw 'VALIDATION-AUTO01.11: silent launcher content invalid.'
    }
}


# ARM-CLEAN06.4U: remove ONLY the known generated VS upgrade report from
# the detached validation worktree. Keep a hash-verified private copy.
# This executes from the remote SHA before UEValidationAgent checks dirty state.
function Move-ARM4UUpgradeLogOutOfValidation {
    param([string]$RepositoryRoot, [string]$StateRoot)
    try {
        $ExpectedParent='fcf13df12f31e5da4018fc10d2b621d84212b33e'
        $Subject=@(& git -C $RepositoryRoot show -s --format=%s refs/remotes/origin/master)
        $Parent=@(& git -C $RepositoryRoot rev-parse 'refs/remotes/origin/master^')
        if ($LASTEXITCODE -ne 0 -or $Subject.Count -ne 1 -or $Parent.Count -ne 1 -or
            ([string]$Subject[0]).Trim() -cne
             'feat(ARM-CLEAN06.4U): migrate authored nonarm QuickItems into real action catalogue' -or
            ([string]$Parent[0]).Trim() -cne $ExpectedParent) {
            return
        }
        $Validation=Join-Path (Split-Path -Parent $RepositoryRoot) 'GrimrockPrototype_UEValidation'
        if (-not (Test-Path -LiteralPath (Join-Path $Validation '.git'))) { return }
        $Top=@(& git -C $Validation rev-parse --show-toplevel)
        $Head=@(& git -C $Validation rev-parse HEAD)
        $Branch=@(& git -C $Validation branch --show-current)
        if ($LASTEXITCODE -ne 0 -or $Top.Count -ne 1 -or $Head.Count -ne 1 -or
            ([string]$Head[0]).Trim() -cne $ExpectedParent -or
            [IO.Path]::GetFullPath(([string]$Top[0]).Replace('/','\')).TrimEnd('\') -ine
             [IO.Path]::GetFullPath($Validation).TrimEnd('\') -or
            @($Branch | Where-Object { -not [string]::IsNullOrWhiteSpace([string]$_) }).Count -ne 0) {
            return
        }
        $Dirty=@(& git -C $Validation status --porcelain --untracked-files=all)
        if ($LASTEXITCODE -ne 0 -or $Dirty.Count -ne 1 -or
            ([string]$Dirty[0]) -cne '?? UpgradeLog.htm') {
            return
        }
        $Source=Join-Path $Validation 'UpgradeLog.htm'
        if (-not (Test-Path -LiteralPath $Source -PathType Leaf) -or
            (((Get-Item -LiteralPath $Source).Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0)) {
            return
        }
        $Backup=Join-Path $StateRoot ('Recovery\ARM4U-UpgradeLog-' +
            (Get-Date -Format 'yyyyMMddHHmmssfff'))
        New-Item -ItemType Directory -Path $Backup -ErrorAction Stop | Out-Null
        $Destination=Join-Path $Backup 'UpgradeLog.htm'
        Copy-Item -LiteralPath $Source -Destination $Destination -ErrorAction Stop
        if ((Get-FileHash -LiteralPath $Source -Algorithm SHA256).Hash -cne
            (Get-FileHash -LiteralPath $Destination -Algorithm SHA256).Hash) {
            throw 'Upgrade log private backup failed SHA-256 verification.'
        }
        $BeforeRemove=@(& git -C $Validation status --porcelain --untracked-files=all)
        if ($LASTEXITCODE -ne 0 -or $BeforeRemove.Count -ne 1 -or
            ([string]$BeforeRemove[0]) -cne '?? UpgradeLog.htm') {
            return
        }
        Remove-Item -LiteralPath $Source -Force -ErrorAction Stop
        $After=@(& git -C $Validation status --porcelain --untracked-files=all)
        if ($LASTEXITCODE -ne 0 -or $After.Count -ne 0) {
            throw 'Dedicated validation worktree still dirty after UpgradeLog relocation.'
        }
        Write-Host '[ARM-CLEAN06.4U] UpgradeLog.htm preserved privately; dedicated worktree clean.'
    }
    catch {
        Write-Warning '[ARM-CLEAN06.4U] UpgradeLog-only recovery declined; no general reset or clean.'
    }
}

# ARM-CLEAN06.4U: preserve and restore ONLY the failed five editor-output
# binaries in the detached Windows validation worktree. No general cleanup.
function Recover-ARM4UReopenFailure {
 param([string]$RepositoryRoot,[string]$StateRoot)
 try {
  $Previous='a414ee67c933c0c4754db649ca79aa9b51c67f6d'
  $Subject=@(& git -C $RepositoryRoot show -s --format=%s refs/remotes/origin/master)
  $Parent=@(& git -C $RepositoryRoot rev-parse 'refs/remotes/origin/master^')
  if($LASTEXITCODE -ne 0 -or $Subject.Count -ne 1 -or $Parent.Count -ne 1 -or
   ([string]$Parent[0]).Trim() -cne 'fcf13df12f31e5da4018fc10d2b621d84212b33e' -or
   ([string]$Subject[0]).Trim() -cne
   'feat(ARM-CLEAN06.4U): migrate authored nonarm QuickItems into real action catalogue') {return}
  $Worktree=Join-Path (Split-Path -Parent $RepositoryRoot) 'GrimrockPrototype_UEValidation'
  $Top=@(& git -C $Worktree rev-parse --show-toplevel)
  $Head=@(& git -C $Worktree rev-parse HEAD)
  $Branch=@(& git -C $Worktree branch --show-current)
  if($LASTEXITCODE -ne 0 -or $Top.Count -ne 1 -or $Head.Count -ne 1 -or
   ([string]$Head[0]).Trim() -cne $Previous -or
   [IO.Path]::GetFullPath(([string]$Top[0]).Replace('/','\')).TrimEnd('\') -ine
   [IO.Path]::GetFullPath($Worktree).TrimEnd('\') -or
   @($Branch | Where-Object {-not [string]::IsNullOrWhiteSpace([string]$_)}).Count -ne 0) {return}
  # The previous editor run may have produced a private report in a
  # different retry folder. The exact detached HEAD, 2 tracked binary paths
  # and 3 new definition paths are the authoritative recovery allowlist.
  $Dirty=@(& git -C $Worktree status --porcelain --untracked-files=all)
  if($LASTEXITCODE -ne 0 -or $Dirty.Count -ne 5) {return}
  $Prefix='Content/GrimrockPrototype/Core/DataAssets/CanonicalStage/'
  $Known=@($Prefix+'DA_ItemSystem.uasset',$Prefix+'DA_ActionCatalogue.uasset')
  $Files=New-Object System.Collections.ArrayList
  $Seen=New-Object System.Collections.Hashtable
  $NewCount=0
  foreach($Record in $Dirty) {
   $Record=[string]$Record
   if($Record.Length -lt 4) {return}
   $Status=$Record.Substring(0,2)
   $Rel=$Record.Substring(3).Replace('\','/')
   if($Seen.ContainsKey($Rel)) {return}
   if($Rel -cin $Known) {if($Status -cne ' M') {return}}
   elseif($Rel -cmatch '^Content/GrimrockPrototype/Core/DataAssets/CanonicalStage/Definitions/DA_Canonical_[A-Za-z0-9_]+\.uasset$') {
    if($Status -cne '??') {return}
    ++$NewCount
   } else {return}
   $File=Join-Path $Worktree $Rel.Replace('/','\')
   if(-not (Test-Path -LiteralPath $File -PathType Leaf) -or
    (((Get-Item -LiteralPath $File).Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0)) {return}
   $Seen[$Rel]=$true
   [void]$Files.Add([pscustomobject]@{Rel=$Rel;File=$File;New=($Status -ceq '??')})
  }
  if($NewCount -ne 3 -or -not $Seen.ContainsKey($Known[0]) -or
   -not $Seen.ContainsKey($Known[1])) {return}
  $Recovery=Join-Path $StateRoot ('Recovery\ARM4U-reopen-'+(Get-Date -Format 'yyyyMMddHHmmssfff'))
  foreach($Item in $Files) {
   $Dest=Join-Path $Recovery $Item.Rel.Replace('/','\')
   New-Item -ItemType Directory -Path (Split-Path -Parent $Dest) -Force -ErrorAction Stop | Out-Null
   Copy-Item -LiteralPath $Item.File -Destination $Dest -ErrorAction Stop
   if((Get-FileHash -LiteralPath $Item.File -Algorithm SHA256).Hash -cne
    (Get-FileHash -LiteralPath $Dest -Algorithm SHA256).Hash) {throw 'Private backup hash mismatch'}
  }
  $Again=@(& git -C $Worktree status --porcelain --untracked-files=all)
  if($LASTEXITCODE -ne 0 -or (@($Again) -join '|') -cne (@($Dirty) -join '|')) {return}
  foreach($Item in $Files) {
   if($Item.New) {Remove-Item -LiteralPath $Item.File -Force -ErrorAction Stop}
   else {
    & git -C $Worktree restore --source=HEAD --worktree -- $Item.Rel | Out-Null
    if($LASTEXITCODE -ne 0) {throw 'Targeted file restore failed'}
   }
  }
  $After=@(& git -C $Worktree status --porcelain --untracked-files=all)
  if($LASTEXITCODE -ne 0 -or $After.Count -ne 0) {throw 'Residual worktree edits'}
  Write-Host '[ARM-CLEAN06.4U] Five editor assets restored after private SHA-verified backups.'
 } catch {Write-Warning '[ARM-CLEAN06.4U] Targeted asset recovery declined; no broad git reset/clean.'}
}

function Set-UEValidationSilentTask {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory=$true)][string]$RepositoryRoot,
        [Parameter(Mandatory=$true)][string]$StateRoot,
        [string]$TaskName = 'GrimrockPrototype-UEValidation'
    )
    Import-Module ScheduledTasks -ErrorAction Stop
    $Task = Get-ScheduledTask -TaskPath '\' -TaskName $TaskName -ErrorAction Stop
    if (@($Task.Actions).Count -ne 1) {
        throw 'VALIDATION-AUTO01.11: unexpected task action count.'
    }
    $Original = $Task.Actions[0]
    $Paths = Get-UEValidationSilentPaths -StateRoot $StateRoot
    if ($Original.Execute -ieq $Paths.WScript) {
        Assert-UEValidationSilentAction -Action $Original -RepositoryRoot $RepositoryRoot -StateRoot $StateRoot
        Move-ARM4UUpgradeLogOutOfValidation -RepositoryRoot $RepositoryRoot -StateRoot $StateRoot
        Recover-ARM4UReopenFailure -RepositoryRoot $RepositoryRoot -StateRoot $StateRoot
        return 'ALREADY_SILENT'
    }
    if ($Original.Execute -ine $Paths.PowerShell -or $Original.WorkingDirectory -ine $RepositoryRoot) {
        throw 'VALIDATION-AUTO01.11: unrelated task action; migration refused.'
    }
    $NewAction = New-UEValidationSilentAction -RepositoryRoot $RepositoryRoot -StateRoot $StateRoot `
        -PowerShellArguments $Original.Arguments
    try {
        # Only update the action: retain the three-minute trigger, principal and settings.
        # Microsoft permits this while an old task instance is running.
        Set-ScheduledTask -TaskPath '\' -TaskName $TaskName -Action $NewAction -ErrorAction Stop | Out-Null
        $Verified = Get-ScheduledTask -TaskPath '\' -TaskName $TaskName -ErrorAction Stop
        if (@($Verified.Actions).Count -ne 1) {
            throw 'VALIDATION-AUTO01.11: task action count changed.'
        }
        Assert-UEValidationSilentAction -Action $Verified.Actions[0] `
            -RepositoryRoot $RepositoryRoot -StateRoot $StateRoot
    }
    catch {
        # Preserve the original known-good PowerShell action if the update/read-back failed.
        try { Set-ScheduledTask -TaskPath '\' -TaskName $TaskName -Action $Original -ErrorAction Stop | Out-Null }
        catch { Write-Warning 'VALIDATION-AUTO01.11: task action rollback failed; inspect local task.' }
        throw
    }
    return 'MIGRATED'
}
