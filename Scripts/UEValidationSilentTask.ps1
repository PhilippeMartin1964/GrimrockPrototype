# VALIDATION-AUTO01.11 — silent Windows Task Scheduler action; Windows PowerShell 5.1.
# The generated launcher lives in the user's local state, not in the project checkout.
# WScript.Shell.Run(..., 0, True): no visible console AND keep task alive until build ends.

function Get-UEValidationSilentPaths {
    param([Parameter(Mandatory=$true)][string]$StateRoot)
    return @{
        PowerShell = (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe')
        WScript = (Join-Path $env:SystemRoot 'System32\wscript.exe')
        Launcher = (Join-Path $StateRoot 'UEValidationSilentLauncher.vbs')
    }
}

function New-UEValidationSilentAction {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory=$true)][string]$RepositoryRoot,
        [Parameter(Mandatory=$true)][string]$StateRoot,
        [Parameter(Mandatory=$true)][string]$PowerShellArguments
    )
    $Paths = Get-UEValidationSilentPaths -StateRoot $StateRoot
    foreach ($Executable in @($Paths.PowerShell, $Paths.WScript)) {
        if (-not (Test-Path -LiteralPath $Executable -PathType Leaf)) {
            throw 'VALIDATION-AUTO01.11: Windows scripting executable unavailable.'
        }
    }
    if ([string]::IsNullOrWhiteSpace($PowerShellArguments) -or $PowerShellArguments.Contains("`r") -or
        $PowerShellArguments.Contains("`n")) {
        throw 'VALIDATION-AUTO01.11: invalid PowerShell arguments.'
    }

    $Bootstrap = Join-Path $RepositoryRoot 'Scripts\UEValidationBootstrap.ps1'
    $Required = @(
        ('-File "' + $Bootstrap + '"'),
        ('-RepositoryRoot "' + $RepositoryRoot + '"'),
        ('-StateRoot "' + $StateRoot + '"')
    )
    foreach ($Token in $Required) {
        if ($PowerShellArguments.IndexOf($Token, [StringComparison]::OrdinalIgnoreCase) -lt 0) {
            throw 'VALIDATION-AUTO01.11: unexpected bootstrap command; no task mutation.'
        }
    }
    $Command = '"' + $Paths.PowerShell + '" ' + $PowerShellArguments
    $ProbeCommand = '"' + $Paths.PowerShell + '" -NoLogo -NoProfile -NonInteractive -Command "exit 0"'
    $EncodedCommand = $Command.Replace('"', '""')
    $EncodedProbe = $ProbeCommand.Replace('"', '""')
    $Source = @(
        "' VALIDATION-AUTO01.11 / GrimrockPrototype / generated by trusted installer or validation agent",
        'Option Explicit',
        'Dim Runner, ExitCode',
        'Set Runner = CreateObject("WScript.Shell")',
        'If WScript.Arguments.Count = 1 Then',
        '    If WScript.Arguments(0) = "--self-test" Then',
        ('        ExitCode = Runner.Run("' + $EncodedProbe + '", 0, True)'),
        '        WScript.Quit ExitCode',
        '    End If',
        'End If',
        ('ExitCode = Runner.Run("' + $EncodedCommand + '", 0, True)'),
        'WScript.Quit ExitCode'
    ) -join "`r`n"

    New-Item -ItemType Directory -Path $StateRoot -Force | Out-Null
    $PreviousSource = $null
    if (Test-Path -LiteralPath $Paths.Launcher -PathType Leaf) {
        $PreviousSource = Get-Content -LiteralPath $Paths.Launcher -Raw -ErrorAction Stop
        if (-not $PreviousSource.StartsWith("' VALIDATION-AUTO01.11 / GrimrockPrototype /")) {
            throw 'VALIDATION-AUTO01.11: unknown existing launcher; overwrite refused.'
        }
    }
    $Temp = $Paths.Launcher + '.tmp'
    try {
        # Unicode BOM keeps absolute paths intact, including accented Windows user names.
        Set-Content -LiteralPath $Temp -Value $Source -Encoding Unicode -ErrorAction Stop
        Move-Item -LiteralPath $Temp -Destination $Paths.Launcher -Force -ErrorAction Stop
        $SelfTestArgs = '//B //Nologo "' + $Paths.Launcher + '" --self-test'
        $Probe = Start-Process -FilePath $Paths.WScript -ArgumentList $SelfTestArgs -WindowStyle Hidden `
            -Wait -PassThru -ErrorAction Stop
        if ($Probe.ExitCode -ne 0) {
            throw 'VALIDATION-AUTO01.11: WSH launcher self-test failed.'
        }
    }
    catch {
        if ($null -ne $PreviousSource) {
            Set-Content -LiteralPath $Paths.Launcher -Value $PreviousSource -Encoding Unicode
        }
        else {
            Remove-Item -LiteralPath $Paths.Launcher -Force -ErrorAction SilentlyContinue
        }
        throw
    }
    finally {
        Remove-Item -LiteralPath $Temp -Force -ErrorAction SilentlyContinue
    }
    return New-ScheduledTaskAction -Execute $Paths.WScript `
        -Argument ('//B //Nologo "' + $Paths.Launcher + '"') -WorkingDirectory $RepositoryRoot
}

function Assert-UEValidationSilentAction {
    param(
        [Parameter(Mandatory=$true)]$Action,
        [Parameter(Mandatory=$true)][string]$RepositoryRoot,
        [Parameter(Mandatory=$true)][string]$StateRoot
    )
    $Paths = Get-UEValidationSilentPaths -StateRoot $StateRoot
    $ExpectedArgs = '//B //Nologo "' + $Paths.Launcher + '"'
    if ($Action.Execute -ine $Paths.WScript -or $Action.Arguments -cne $ExpectedArgs -or
        $Action.WorkingDirectory -ine $RepositoryRoot -or
        -not (Test-Path -LiteralPath $Paths.Launcher -PathType Leaf)) {
        throw 'VALIDATION-AUTO01.11: scheduled task action does not match silent launcher.'
    }
    $Content = Get-Content -LiteralPath $Paths.Launcher -Raw -ErrorAction Stop
    if (-not $Content.StartsWith("' VALIDATION-AUTO01.11 / GrimrockPrototype /") -or
        -not $Content.Contains('Runner.Run(') -or
        -not $Content.Contains(', 0, True)') -or
        -not $Content.Contains('UEValidationBootstrap.ps1')) {
        throw 'VALIDATION-AUTO01.11: silent launcher content invalid.'
    }
}

function Set-UEValidationSilentTask {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory=$true)][string]$RepositoryRoot,
        [Parameter(Mandatory=$true)][string]$StateRoot,
        [string]$TaskName = 'GrimrockPrototype-UEValidation'
    )
    Import-Module ScheduledTasks -ErrorAction Stop
    $Task = Get-ScheduledTask -TaskPath '\' -TaskName $TaskName -ErrorAction Stop
    if (@($Task.Actions).Count -ne 1) {
        throw 'VALIDATION-AUTO01.11: unexpected task action count.'
    }
    $Original = $Task.Actions[0]
    $Paths = Get-UEValidationSilentPaths -StateRoot $StateRoot
    if ($Original.Execute -ieq $Paths.WScript) {
        Assert-UEValidationSilentAction -Action $Original -RepositoryRoot $RepositoryRoot -StateRoot $StateRoot
        return 'ALREADY_SILENT'
    }
    if ($Original.Execute -ine $Paths.PowerShell -or $Original.WorkingDirectory -ine $RepositoryRoot) {
        throw 'VALIDATION-AUTO01.11: unrelated task action; migration refused.'
    }
    $NewAction = New-UEValidationSilentAction -RepositoryRoot $RepositoryRoot -StateRoot $StateRoot `
        -PowerShellArguments $Original.Arguments
    try {
        # Only update the action: retain the three-minute trigger, principal and settings.
        # Microsoft permits this while an old task instance is running.
        Set-ScheduledTask -TaskPath '\' -TaskName $TaskName -Action $NewAction -ErrorAction Stop | Out-Null
        $Verified = Get-ScheduledTask -TaskPath '\' -TaskName $TaskName -ErrorAction Stop
        if (@($Verified.Actions).Count -ne 1) {
            throw 'VALIDATION-AUTO01.11: task action count changed.'
        }
        Assert-UEValidationSilentAction -Action $Verified.Actions[0] `
            -RepositoryRoot $RepositoryRoot -StateRoot $StateRoot
    }
    catch {
        # Preserve the original known-good PowerShell action if the update/read-back failed.
        try { Set-ScheduledTask -TaskPath '\' -TaskName $TaskName -Action $Original -ErrorAction Stop | Out-Null }
        catch { Write-Warning 'VALIDATION-AUTO01.11: task action rollback failed; inspect local task.' }
        throw
    }
    return 'MIGRATED'
}
